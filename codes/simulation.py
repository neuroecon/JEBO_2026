import hddm
from patsy import dmatrix  # for generation of (regression) design matrices
import numpy as np         # for basic matrix operations
from pandas import Series  # to manipulate data-frames generated by hddm


n_subjects = 1
trials_per_level = 1000 # and per stimulus


level1a = {'v':.3, 'a':2, 't':.3}
level2a = {'v':.4, 'a':2, 't':.3}
level3a = {'v':.5, 'a':2, 't':.3}
data, params_a = hddm.generate.gen_rand_data({'level1': level1a,
                                                'level2': level2a,
                                                'level3': level3a},
                                                size=trials_per_level,
                                                subjs=n_subjects)

data_false=data
data_false["rt"]=np.random.rand(data_false.shape[0])+3

v_reg = {'model': 'v ~ condition', 'link_func': lambda x: x}
ddm_model=hddm.HDDMRegressor(data_false, v_reg,informative=False)
ddm_model.sample(10000,burn=2000)

ddm_model.print_stats()











